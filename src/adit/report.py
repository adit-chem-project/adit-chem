class ReportError(AditValueError):
    pass


@dataclass
class RunReport:

    run_dir: Path
    spec: object | None = None
    provenance: dict = field(default_factory=dict)
    code_version: str = ""
    analysis_summary: str = ""
    notes: list[str] = field(default_factory=list)

    @property
    def code(self) -> str:
        return self.spec.method.code if self.spec is not None else ""


def code_display_name(code: str) -> str:
    from adit.project import code_display_name as _name

    return _name(code)


def tidy_version(text: str) -> str:
    import re

    line = re.sub(r"\s+", " ", text).strip()
    line = re.sub(r"^adit-[a-z0-9]+:\s*", "", line)
    return line.strip(" .*|\t")




def load_run_report(run_dir: Path | str) -> RunReport:
    """Read one run directory. Raises ReportError when spec.json is missing."""
    from adit.spec import CalculationSpec

    d = Path(run_dir).expanduser()
    if not d.is_dir():
        raise ReportError(L(f"ディレクトリがありません: {d}", f"directory not found: {d}"))
    spec_path = d / "spec.json"
    if not spec_path.is_file():
        raise ReportError(L(f"{d} に spec.json がありません (ADIT が生成したディレクトリを指定してください)",
                            f"{d} has no spec.json (give a directory generated by ADIT)"))
    try:
        spec = CalculationSpec.load(spec_path)
    except Exception as ex:
        raise ReportError(L(f"{spec_path} を読めません: {ex}", f"cannot read {spec_path}: {ex}")) from ex
    report = RunReport(run_dir=d, spec=spec, provenance=read_provenance(d) or {})
    version_file = d / "code_version.txt"
    if version_file.is_file():
        text = version_file.read_text(encoding="utf-8", errors="replace").strip()
        report.code_version = tidy_version(text.splitlines()[0]) if text else ""
    if not report.code_version:
        report.notes.append(L("計算コードのバージョンは未記録です (実行する前か、この計算コードのバージョンの行を確かめていません)",
                              "the code version is not recorded (the run has not finished, or the version line of this code was not verified)"))
    summary = d / "analysis" / "summary.txt"
    if summary.is_file():
        report.analysis_summary = summary.read_text(encoding="utf-8", errors="replace").strip()
    if not report.provenance:
        report.notes.append(L("作成時の記録 (生成した ADIT のバージョン・ファイルの照合用のハッシュ) が spec.json にありません",
                              "the provenance (ADIT version, file fingerprints) is not in spec.json"))
    return report


def _unit_of(name: str, spec=None) -> str:
    for suffix, unit in _UNITS:
        if name.endswith(suffix):
            return unit
    if spec is not None:
        table = _CODE_UNITS.get(spec.method.code, {})
        unit = table.get(name, "")
        if isinstance(unit, dict):
            return unit.get(getattr(spec.method, "tolerance", ""), "")
        return unit
    return ""


def _is_empty(value) -> bool:
    return value is None or value == "" or value == {} or value == [] or value is False


def _value_text(value, machine: bool = False) -> str:
    if isinstance(value, bool):
        return ("true" if value else "false") if machine else (L("はい", "yes") if value else L("いいえ", "no"))
    if isinstance(value, float):
        return f"{value:g}"
    if isinstance(value, (list, tuple)):
        return ", ".join(_value_text(v, machine) for v in value)
    if isinstance(value, dict):
        return ", ".join(f"{k}: {_value_text(v, machine)}" for k, v in value.items())
    return str(value)


def condition_rows(report: RunReport, machine: bool = False) -> list[tuple[str, str, str]]:
    spec = report.spec
    if spec is None:
        return []
    rows: list[tuple[str, str, str]] = []
    method = spec.method.model_dump(mode="json")
    for name, value in method.items():
        if name in _SKIP_METHOD_FIELDS or _is_empty(value):
            continue
        if isinstance(value, (int, float)) and not isinstance(value, bool) and value == 0 and "seed" not in name:
            continue
        rows.append((f"method.{name}", _value_text(value, machine), _unit_of(name, spec)))
    task = spec.task.model_dump(mode="json")
    skip = set(unapplied_rows(report))
    for name in _TASK_FIELDS:
        value = task.get(name)
        if _is_empty(value) or f"task.{name}" in skip:
            continue
        rows.append((f"task.{name}", _value_text(value, machine), _unit_of(name)))
    if task.get("type") == "molecular_dynamics":
        md = task.get("md") or {}
        for name in _MD_FIELDS:
            if not _is_empty(md.get(name)) and f"task.md.{name}" not in skip:
                rows.append((f"task.md.{name}", _value_text(md[name], machine), _unit_of(name)))
    if spec.kpoints is not None:
        kp = spec.kpoints.model_dump(mode="json")
        rows.append(("kpoints.mode", _value_text(kp["mode"]), ""))
        if kp["mode"] == "mesh":
            rows.append(("kpoints.mesh", "×".join(str(x) for x in kp["mesh"]), ""))
            rows.append(("kpoints.shift", _value_text(kp["shift"]), ""))
        elif kp["mode"] == "density":
            rows.append(("kpoints.density", _value_text(kp["density"]), "1/Å"))
    rows.append(("structure.source", _value_text(spec.structure.source, machine), ""))
    if spec.structure.source_ref.strip():
        ref = spec.structure.source_ref.strip()
        rows.append(("structure.source_ref", ref if len(ref) <= 120 else ref[:120] + " …", ""))
    if spec.plumed is not None:
        rows.append(("plumed", L("あり (plumed.dat。集合変数は利用者が書いたもの)",
                                 "yes (plumed.dat; the collective variables are the user's)"), ""))
    return rows


def _pw_in_pseudos(run_dir: Path) -> set[str]:
    path = run_dir / "pw.in"
    if not path.is_file():
        return set()
    names: set[str] = set()
    inside = False
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.upper().startswith("ATOMIC_SPECIES"):
            inside = True
            continue
        if inside:
            if line[0] in "&/" or line.split()[0].isupper() and len(line.split()) <= 2:
                break
            parts = line.split()
            if len(parts) >= 3:
                names.add(parts[2])
            else:
                break
    return names


def parameter_rows(report: RunReport) -> list[tuple[str, str, str]]:
    d = report.run_dir
    rows: list[tuple[str, str, str]] = []
    for path in sorted(d.rglob("*")):
        if not path.is_file():
            continue
        name = path.relative_to(d).as_posix()
        if path.suffix.upper() == ".UPF":
            from adit.codes.upf import UpfError, read_upf_header

            try:
                head = read_upf_header(path)
            except UpfError as ex:
                rows.append((name, L("ヘッダを読めません", "cannot read the header"), str(ex)))
                continue
            rows.append((name, head.element,
                         L(f"汎関数 {head.functional or '(記載なし)'}、価電子 {head.z_valence:g}、種類 {head.pseudo_type or '(記載なし)'}",
                           f"functional {head.functional or '(not stated)'}, valence {head.z_valence:g}, type {head.pseudo_type or '(not stated)'}")))
        elif path.suffix.lower() in (".pspnc", ".psp8", ".psp", ".fhi"):
            from adit.codes.abinit_psp import AbinitPspError, describe, read_psp_header

            try:
                psp = read_psp_header(path)
            except AbinitPspError as ex:
                rows.append((name, L("ヘッダを読めません", "cannot read the header"), str(ex)))
                continue
            rows.append((name, psp.title, describe(psp)))
        elif path.name == "POTCAR" or path.name.startswith("POTCAR"):
            from adit.codes.potcar import PotcarError, read_potcar_header

            try:
                head = read_potcar_header(path)
            except PotcarError as ex:
                rows.append((name, L("ヘッダを読めません", "cannot read the header"), str(ex)))
                continue
            rows.append((name, head.titel, L(f"価電子 {head.zval:g}、ENMAX {head.enmax:g} eV",
                                             f"valence {head.zval:g}, ENMAX {head.enmax:g} eV")))
    return rows


def parameter_notes(report: RunReport) -> list[str]:
    spec = report.spec
    if spec is None:
        return []
    out: list[str] = []
    method = spec.method.model_dump(mode="json")
    if spec.method.code == "espresso":
        referenced = sorted(set(method.get("pseudo", {}).values()) | _pw_in_pseudos(report.run_dir))
        missing = [n for n in referenced if not (report.run_dir / "pseudo" / n).is_file()]
        if missing:
            out.append(L(f"入力が参照する擬ポテンシャル {', '.join(missing)} は、このディレクトリにありません。"
                         "汎関数はファイルのヘッダにしか書かれていないので、この報告からは特定できません。",
                         f"the pseudopotentials referenced by the input ({', '.join(missing)}) are not in this directory; "
                         "the functional is recorded only in those files, so it cannot be identified from this report."))
    if spec.method.code == "vasp":
        out.append(L("VASP の POTCAR はライセンスのため生成先へ写しません。使った POTCAR の TITEL (汎関数を含む) は、"
                     "計算した環境の POTCAR か OUTCAR で確かめてください。",
                     "VASP POTCAR files are not copied into the generated directory for licensing reasons; check the TITEL "
                     "line (which names the functional) in the POTCAR or OUTCAR of the machine that ran the calculation."))
    if spec.method.code == "dftbplus":
        out.append(L("Slater-Koster のパラメータに交換相関汎関数の記載はありません (DFTB のパラメータ化そのものが近似です)。"
                     "使ったセットの名前と照合用のハッシュは上の表にあります。",
                     "Slater-Koster parameters record no exchange-correlation functional (the parameterization itself is the "
                     "approximation); the set name and fingerprints are in the table above."))
    return out


def runtime_rows(report: RunReport) -> list[tuple[str, str, str]]:
    spec = report.spec
    if spec is None:
        return []
    r = spec.runtime.model_dump(mode="json")
    rows = [("runtime.profile", _value_text(r["profile"]), ""),
            ("runtime.nodes", _value_text(r["nodes"]), ""),
            ("runtime.ncpus", _value_text(r["ncpus"]), ""),
            ("runtime.mpiprocs", _value_text(r["mpiprocs"]), L("プロセス", "processes")),
            ("runtime.omp_threads", _value_text(r["omp_threads"]), L("スレッド", "threads"))]
    if r.get("walltime"):
        rows.append(("runtime.walltime", _value_text(r["walltime"]), ""))
    return rows


def unapplied_rows(report: RunReport) -> dict[str, dict]:
    from adit.applied import unapplied_settings

    return unapplied_settings(report.spec) if report.spec is not None else {}


def structure_sentence(report: RunReport) -> str:
    spec = report.spec
    atoms = spec.atoms
    formula = atoms.get_chemical_formula()
    n = len(atoms)
    if all(atoms.pbc):
        cell = atoms.cell.cellpar()
        where = L(f"3 方向とも周期的なセル (a, b, c = {cell[0]:.4f}, {cell[1]:.4f}, {cell[2]:.4f} Å、"
                  f"α, β, γ = {cell[3]:.2f}, {cell[4]:.2f}, {cell[5]:.2f}°)",
                  f"a cell periodic in all three directions (a, b, c = {cell[0]:.4f}, {cell[1]:.4f}, {cell[2]:.4f} Å; "
                  f"α, β, γ = {cell[3]:.2f}, {cell[4]:.2f}, {cell[5]:.2f}°)")
    elif any(atoms.pbc):
        where = L(f"一部の方向だけ周期的なセル (pbc = {tuple(bool(x) for x in atoms.pbc)})",
                  f"a cell periodic in some directions only (pbc = {tuple(bool(x) for x in atoms.pbc)})")
    else:
        where = L("非周期 (孤立した分子)", "nonperiodic (an isolated molecule)")
    charge = L(f"全電荷 {spec.structure.charge}、スピン多重度 {spec.structure.multiplicity}",
               f"total charge {spec.structure.charge}, spin multiplicity {spec.structure.multiplicity}")
    return L(f"{formula} ({n} 原子、{where}、{charge})", f"{formula} ({n} atoms, {where}, {charge})")


