def _buttons(ok_text: str, dialog: QDialog) -> tuple[QHBoxLayout, QPushButton, QPushButton]:
    cancel = QPushButton(L("キャンセル", "Cancel")); ok = QPushButton(ok_text); ok.setObjectName("primary"); ok.setDefault(True)
    cancel.clicked.connect(dialog.reject)
    row = QHBoxLayout(); row.addStretch(); row.addWidget(cancel); row.addWidget(ok)
    return row, cancel, ok


def _hint(text: str) -> QLabel:
    w = QLabel(text); w.setObjectName("hint"); w.setWordWrap(True)
    return w


def _folder_row(edit: QLineEdit, title: str, parent: QWidget) -> QHBoxLayout:
    btn = QPushButton(L("参照…", "Browse…"))

    def choose() -> None:
        start = edit.text().strip() or str(Path.home())
        d = QFileDialog.getExistingDirectory(parent, title, str(Path(start).expanduser().parent))
        if d:
            edit.setText(d)
    btn.clicked.connect(choose)
    row = QHBoxLayout(); row.addWidget(edit, 1); row.addWidget(btn)
    edit.browse = btn
    return row


def _generator_error(ex: Exception) -> str:
    from pydantic import ValidationError as PydanticError
    if isinstance(ex, PydanticError):
        from adit.validate_types import friendly_pydantic
        return friendly_pydantic(ex)
    return str(ex)


class ContinueDialog(QDialog):

    def __init__(self, make_conditions: Callable, default_dir: str = "", parent: QWidget | None = None):
        super().__init__(parent)
        self.setWindowTitle(L("前の計算の続きを作る", "Continue a previous calculation"))
        self.make_conditions = make_conditions
        self.spec = None
        self.folder = QLineEdit(default_dir); self.folder.setPlaceholderText(L("前の計算のディレクトリ (中に spec.json がある)", "directory of the previous run (contains spec.json)"))
        self.found = _hint("")
        self.velocities = QCheckBox(L("速度を引き継ぐ (前も今回も MD のとき)", "Carry over the velocities (when both runs are MD)")); self.velocities.setChecked(True)
        self.keep = QCheckBox(L("計算の条件はいまの画面の値を使う (外すと前の計算と同じ条件)", "Use the current settings for the conditions (untick for the previous run's conditions)"))
        self.table = _hint(carry_table())
        self.table.setMinimumHeight(self.table.fontMetrics().lineSpacing() * 10 + 12)
        row, _, self.btn_ok = _buttons(L("続きを作る", "Continue"), self)
        form = QFormLayout(); form.setVerticalSpacing(ROW_SPACING)
        add_row(form, L("前の計算のディレクトリ", "Previous run directory"), _folder_row(self.folder, L("前の計算のディレクトリ", "Previous run directory"), self),
                help_text=L("ADIT が生成して、計算が最後まで走ったディレクトリ。最終構造 (MD なら速度も) を読みます。",
                            "A directory generated by ADIT whose calculation has finished; its final structure (and MD velocities) is read."))
        form.addRow(self.found)
        form.addRow(self.velocities); form.addRow(self.keep)
        lay = QVBoxLayout(self); lay.setContentsMargins(PANEL_MARGIN, PANEL_MARGIN, PANEL_MARGIN, PANEL_MARGIN); lay.setSpacing(GROUP_SPACING)
        lay.addLayout(form); lay.addWidget(self.table); lay.addLayout(row)
        self.setMinimumWidth(680)
        self.folder.textChanged.connect(self._look)
        self.btn_ok.clicked.connect(self.make)
        self._look()

    def _look(self, *_) -> None:
        from adit.spec import CalculationSpec
        d = Path(self.folder.text().strip()).expanduser()
        if not self.folder.text().strip():
            self.found.setText(""); return
        sp = d / "spec.json"
        if not sp.is_file():
            self.found.setText(L(f"{d} に spec.json がありません", f"{d} has no spec.json")); return
        try:
            prev = CalculationSpec.load(sp)
        except Exception as ex:
            self.found.setText(L(f"spec.json を読めません: {ex}", f"cannot read spec.json: {ex}")); return
        from adit.stages import _describe
        self.found.setText(L(f"前の計算: {prev.method.code}、{_describe(prev)}、{len(prev.structure.atoms.symbols)} 原子",
                             f"Previous run: {prev.method.code}, {_describe(prev)}, {len(prev.structure.atoms.symbols)} atoms"))

    def make(self) -> None:
        from adit.continuation import ContinuationError, continue_from
        from adit.project import ProjectError
        if not self.folder.text().strip():
            QMessageBox.warning(self, L("続きを作れません", "Cannot continue"), L("前の計算のディレクトリを指定してください。", "Choose the previous run directory.")); return
        try:
            cond = self.make_conditions() if self.keep.isChecked() else None
            self.spec = continue_from(self.folder.text().strip(), cond, velocities=self.velocities.isChecked())
        except (ContinuationError, ProjectError, ValueError, OSError) as ex:
            QMessageBox.critical(self, L("続きを作れません", "Cannot continue"), _generator_error(ex)); return
        self.accept()

    def summary(self) -> str:
        return continuation_summary(self.spec) if self.spec is not None else ""


