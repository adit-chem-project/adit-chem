def _floats(text: str) -> tuple[float, ...]:
    try:
        return tuple(float(x) for x in text.split(",") if x.strip())
    except ValueError as ex:
        raise ValueError(L(f"数をカンマで区切って書いてください: {text!r}", f"write numbers separated by commas: {text!r}")) from ex


def _thermo_options(a):
    if a.thermo is None:
        return None
    from adit.analysis.thermo import ThermoOptions
    return ThermoOptions(model=a.thermo, temperatures_k=_floats(a.temperature) if a.temperature else (), pressure_pa=a.pressure,
                         symmetry_number=a.symmetry_number, geometry=a.geometry, spin=a.spin, imaginary=a.imaginary,
                         exclude_lowest=a.exclude_lowest, qh_cutoff_cm1=a.qh_cutoff, msrrho_tau_cm1=a.msrrho_tau)


def _uvvis(text: str | None) -> tuple[str, float] | None:
    if not text:
        return None
    from adit.analysis.uvvis import SHAPES
    shape, _, w = text.partition(":")
    try:
        fwhm = float(w)
    except ValueError:
        fwhm = None
    if shape.strip() not in SHAPES or fwhm is None or fwhm <= 0:
        raise ValueError(L(f"--uvvis は「形:半値全幅」の形です (形は {' / '.join(SHAPES)}、幅は正の数 [eV]。例 gauss:0.3): {text!r}",
                           f"--uvvis takes shape:FWHM (shape {' / '.join(SHAPES)}, positive width in eV; e.g. gauss:0.3): {text!r}"))
    return shape.strip(), fwhm


