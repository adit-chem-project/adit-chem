_HIDDEN: list = []


def _hide_detailed_options(parser, argv) -> None:
    if argv is not None and "--help-all" in argv:
        return
    import sys as _sys

    if argv is None and "--help-all" in _sys.argv[1:]:
        return
    for action in parser._actions:
        names = set(action.option_strings)
        if not names or names & set(COMMON_OPTIONS) or "--help" in names:
            continue
        _HIDDEN.append((action, action.help))
        action.help = argparse.SUPPRESS


def _show_all_options(parser) -> None:
    for action, text in _HIDDEN:
        action.help = text
    _HIDDEN.clear()
    parser.print_help()


def _msd_fit_range(values, parser):
    if not values:
        return None
    parts: list[str] = []
    for v in values:
        parts += [x for x in str(v).replace("、", ",").split(",") if x.strip()]
    try:
        nums = [float(x) for x in parts]
    except ValueError:
        parser.error(L("--msd-fit は数を 2 つ (例 --msd-fit 10 45 または --msd-fit 10,45) にしてください",
                       "--msd-fit takes two numbers (e.g. --msd-fit 10 45 or --msd-fit 10,45)"))
    if len(nums) != 2:
        parser.error(L(f"--msd-fit は数を 2 つ にしてください ({len(nums)} 個 受け取りました。例 --msd-fit 10,45)",
                       f"--msd-fit takes two numbers (got {len(nums)}; e.g. --msd-fit 10,45)"))
    if not nums[0] < nums[1]:
        parser.error(L(f"--msd-fit の始め ({nums[0]:g}) は終わり ({nums[1]:g}) より小さくしてください",
                       f"the start of --msd-fit ({nums[0]:g}) must be smaller than the end ({nums[1]:g})"))
    return (nums[0], nums[1])


